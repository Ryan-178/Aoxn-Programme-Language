//! `aoxn test` — discovery of `def test_*` functions and the Aoxn driver
//! that runs them through `stdlib/unittest`.
//!
//! The language has no reflection, so a runner has to be told which
//! functions to call. `Aoxn test <file.ax>` answers that at BUILD time: the
//! entry file's top-level declarations are already in the AST the loader
//! produced, so discovery is a filter over them, and the driver is generated
//! source that imports exactly those functions (`from "<entry>" import ...`)
//! and registers them with the same `ut_suite`/`ut_add`/`ut_run` an
//! hand-written suite uses.
//!
//! Scope is the ENTRY file on purpose: an imported helper that happens to
//! export a name starting with `test_` is not a test of the file under test.
//! That also keeps the answer independent of the import graph.
//!
//! Nothing here calls clang; the CLI builds the generated driver and runs it.

use crate::ast::{FnDecl, Type};
use crate::files;
use std::path::Path;

/// One discovered test: the function's source name and where it is declared.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct TestFn {
    pub name: String,
    pub line: usize,
}

/// The functions `aoxn test` will run: top-level, non-extern `def test_*`
/// with no parameters and a `void` return, declared in one of `entry_files`
/// (the registry names, as `files::name` reports them).
///
/// A signature the driver could not call is an ERROR, not a skip: silently
/// not running a function the author named `test_` is the worst answer.
pub fn collect(funcs: &[FnDecl], entry_files: &[String]) -> Result<Vec<TestFn>, Vec<crate::Diag>> {
    let mut out = Vec::new();
    let mut errs = Vec::new();
    for f in funcs {
        if f.is_extern || !f.name.starts_with("test_") {
            continue;
        }
        let file = files::name(f.pos.file);
        if !entry_files.iter().any(|e| e == &file) {
            continue;
        }
        let err = if !f.params.is_empty() {
            Some(format!(
                "test function '{}' must take no parameters (found {})",
                f.name,
                f.params.len()
            ))
        } else if !f.type_params.is_empty() || f.len_param.is_some() {
            Some(format!("test function '{}' must not be generic", f.name))
        } else if f.ret != Type::Void {
            Some(format!(
                "test function '{}' must return void, not '{}'",
                f.name, f.ret
            ))
        } else {
            None
        };
        match err {
            Some(message) => errs.push(crate::Diag::at(
                "type",
                f.pos.file,
                f.pos.line,
                f.pos.col,
                message,
            )),
            None => out.push(TestFn { name: f.name.clone(), line: f.pos.line }),
        }
    }
    if errs.is_empty() {
        Ok(out)
    } else {
        Err(errs)
    }
}

/// The Aoxn source of the driver that runs `tests` from `entry`.
///
/// The entry is imported by its ABSOLUTE path because the driver itself is
/// written to the build-cache directory, not next to the file under test.
/// A relative import there would resolve against the cache dir.
pub fn driver_source(entry: &Path, tests: &[TestFn]) -> Result<String, String> {
    let path = entry
        .canonicalize()
        .map_err(|e| format!("cannot resolve {}: {}", entry.display(), e))?;
    let path = crate::paths::strip_verbatim(path);
    // the loader accepts '/' on every platform; a backslash would start an
    // escape inside the quoted Aoxn string literal
    let path = path.to_string_lossy().replace('\\', "/");
    if path.contains('"') || path.contains('\n') {
        return Err(format!(
            "the test file's path contains a character an import cannot spell: {path}"
        ));
    }

    let names = tests
        .iter()
        .map(|t| t.name.as_str())
        .collect::<Vec<_>>()
        .join(", ");
    let mut s = String::new();
    s.push_str("# generated by `aoxn test` from ");
    s.push_str(&path);
    s.push_str("\nimport * from \"stdlib/unittest\"\n");
    s.push_str(&format!("from \"{path}\" import {names}\n\n"));
    s.push_str("def main() -> int:\n");
    s.push_str("    s = ut_suite()\n");
    for t in tests {
        s.push_str(&format!("    s = ut_add(s, \"{}\", {})\n", t.name, t.name));
    }
    s.push_str("    r = ut_run(s)\n");
    s.push_str("    return 1 if r.failed > 0 else 0\n");
    Ok(s)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::ast::{Block, Param, Pos};

    fn pos(line: usize, file: u32) -> Pos {
        Pos { line, col: 1, file }
    }

    fn func(name: &str, params: Vec<(&str, Type)>, ret: Type, file: u32, line: usize) -> FnDecl {
        FnDecl {
            name: name.to_string(),
            type_params: Vec::new(),
            len_param: None,
            params: params
                .into_iter()
                .map(|(n, ty)| Param { name: n.to_string(), ty, pos: pos(line, file), default: None })
                .collect(),
            ret,
            body: Block { stmts: Vec::new() },
            is_extern: false,
            pos: pos(line, file),
        }
    }

    #[test]
    fn only_the_entry_files_well_formed_tests_are_collected() {
        let file = crate::files::register("C:/proj/tests.ax");
        let other = crate::files::register("C:/proj/helper.ax");
        let funcs = vec![
            func("test_one", vec![], Type::Void, file, 3),
            func("helper", vec![], Type::Void, file, 6),
            func("test_in_helper", vec![], Type::Void, other, 1),
            func("test_two", vec![], Type::Void, file, 9),
        ];
        let got = collect(&funcs, &["C:/proj/tests.ax".to_string()]).expect("collect");
        assert_eq!(
            got,
            vec![
                TestFn { name: "test_one".into(), line: 3 },
                TestFn { name: "test_two".into(), line: 9 },
            ]
        );
    }

    #[test]
    fn a_test_with_parameters_is_a_diagnostic_not_a_silent_skip() {
        let file = crate::files::register("C:/proj/params.ax");
        let funcs = vec![func("test_bad", vec![("n", Type::Int)], Type::Void, file, 5)];
        let errs = collect(&funcs, &["C:/proj/params.ax".to_string()]).expect_err("must fail");
        assert!(errs[0].message.contains("must take no parameters"), "{}", errs[0].message);
    }

    #[test]
    fn a_test_returning_a_value_is_a_diagnostic() {
        let file = crate::files::register("C:/proj/ret.ax");
        let funcs = vec![func("test_bad", vec![], Type::Int, file, 2)];
        let errs = collect(&funcs, &["C:/proj/ret.ax".to_string()]).expect_err("must fail");
        assert!(errs[0].message.contains("must return void"), "{}", errs[0].message);
    }

    #[test]
    fn the_driver_imports_the_entry_absolutely_and_registers_every_test() {
        let dir = std::env::temp_dir().join(format!("aoxn-testcmd-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&dir);
        std::fs::create_dir_all(&dir).unwrap();
        let entry = dir.join("suite.ax");
        std::fs::write(&entry, "def test_a():\n    pass\n").unwrap();
        let src = driver_source(&entry, &[
            TestFn { name: "test_a".into(), line: 1 },
            TestFn { name: "test_b".into(), line: 4 },
        ])
        .expect("driver");
        assert!(src.contains("import * from \"stdlib/unittest\""));
        let import = src.lines().find(|l| l.starts_with("from \"")).expect("import line");
        assert!(import.ends_with("suite.ax\" import test_a, test_b"), "{import}");
        assert!(!import.contains('\\'), "backslashes must be forward slashes: {import}");
        assert!(src.contains("    s = ut_add(s, \"test_b\", test_b)\n"));
        assert!(src.contains("    return 1 if r.failed > 0 else 0\n"));
        let _ = std::fs::remove_dir_all(&dir);
    }
}
